-- ReduxCoreX Supabase setup
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  avatar_url text,
  created_at timestamptz not null default now()
);

alter table public.profiles add column if not exists display_name text;
update public.profiles set display_name=coalesce(display_name, username) where display_name is null;
create unique index if not exists profiles_username_lower_unique on public.profiles (lower(username));

-- username is the login name; display_name is the visible name.
create or replace function public.get_email_by_username(login_username text)
returns text
language sql
security definer
set search_path = public
as $$
  select u.email
  from public.profiles p
  join auth.users u on u.id=p.id
  where lower(p.username)=lower(trim(login_username))
  limit 1;
$$;
revoke all on function public.get_email_by_username(text) from public;
grant execute on function public.get_email_by_username(text) to anon, authenticated;

create table if not exists public.download_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  item_name text not null,
  category text not null,
  downloaded_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.download_history enable row level security;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles for select using (auth.uid() = id);

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own" on public.profiles for insert with check (auth.uid() = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "history_select_own" on public.download_history;
create policy "history_select_own" on public.download_history for select using (auth.uid() = user_id);

drop policy if exists "history_insert_own" on public.download_history;
create policy "history_insert_own" on public.download_history for insert with check (auth.uid() = user_id);

